import { describe, expect, it } from 'vitest';
import type { Endpoint, HttpMethod } from '../../src/core/types';
import { matchesFilter } from '../../src/core/view';
import { toMarkdown } from '../../src/export/markdown';
import { baseUrlFor, requestTemplate, sampleValue, toCurl, toHttpFile } from '../../src/export/requests';

function ep(method: HttpMethod, p: string, extra: Partial<Endpoint> = {}): Endpoint {
  return {
    id: `${method} ${p}`,
    framework: 'express',
    method,
    path: p,
    pathIsStatic: true,
    location: { file: '/p/src/routes/users.js', line: 7, column: 1 },
    middleware: [],
    services: [],
    parameters: [],
    notes: [],
    projectRoot: '/p',
    ...extra,
  };
}

describe('baseUrlFor', () => {
  const servers = [{ projectRoot: '/p', port: 4000, location: { file: '/p/server.js', line: 1, column: 1 } }];
  it('prefers the setting, then the detected port, then the framework default', () => {
    expect(baseUrlFor(ep('GET', '/'), { baseUrl: 'https://staging.example.com/', servers })).toBe('https://staging.example.com');
    expect(baseUrlFor(ep('GET', '/'), { baseUrl: '', servers })).toBe('http://localhost:4000');
    expect(baseUrlFor(ep('GET', '/', { projectRoot: '/q' }), { baseUrl: '', servers })).toBe('http://localhost:3000');
    expect(baseUrlFor(ep('GET', '/', { projectRoot: '/q', framework: 'spring' }), { baseUrl: '  ', servers })).toBe('http://localhost:8080');
  });
});

describe('requestTemplate', () => {
  it('finds path parameters in Express, NestJS and Spring syntax', () => {
    const fill = (name: string) => `<${name}>`;
    expect(requestTemplate(ep('GET', '/a/:id/b/:slug?/c/:n(\\d+)'), fill).path).toBe('/a/<id>/b/<slug>/c/<n>');
    expect(requestTemplate(ep('GET', '/a/{id}/b/{code:[A-Z]+}/{*rest}'), fill).path).toBe('/a/<id>/b/<code>/<rest>');
    const dynamic = requestTemplate(ep('GET', '/${config.base}/x', { pathIsStatic: false }), fill);
    expect(dynamic.path).toBe('/${config.base}/x');
    expect(dynamic.warnings).toEqual([expect.stringContaining('could not be resolved statically')]);
  });

  it('uses GET for routes that match every method', () => {
    const t = requestTemplate(ep('ALL', '/any'), (n) => n);
    expect(t.method).toBe('GET');
    expect(t.warnings).toEqual([expect.stringContaining('every HTTP method')]);
  });

  it('picks sample values from parameter types', () => {
    expect(sampleValue({ name: 'id', in: 'path', required: true, type: 'Long' })).toBe('1');
    expect(sampleValue({ name: 'id', in: 'path', required: true, type: 'UUID' })).toBe('00000000-0000-0000-0000-000000000000');
    expect(sampleValue({ name: 'q', in: 'query', required: true, type: 'string' })).toBe('example');
    expect(sampleValue()).toBe('1');
  });
});

describe('toCurl', () => {
  it('builds a plain GET', () => {
    expect(toCurl(ep('GET', '/users/:id'), 'http://localhost:3000')).toEqual({ command: "curl 'http://localhost:3000/users/1'", warnings: [] });
  });

  it('adds a JSON body for writes and a bearer token for protected endpoints', () => {
    const e = ep('POST', '/users', { requestBodyType: 'CreateUserDto', auth: { status: 'protected', via: ['authenticate'] } });
    expect(toCurl(e, 'http://h').command).toBe(["curl -X POST 'http://h/users'", '-H "Authorization: Bearer $TOKEN"', "-H 'Content-Type: application/json'", "-d '{}'"].join(' \\\n  '));
  });

  it('includes required query parameters, headers and cookies, and quotes safely', () => {
    const e = ep('GET', "/it's", {
      parameters: [
        { name: 'q', in: 'query', required: true, type: 'string' },
        { name: 'page', in: 'query', required: false },
        { name: 'x-tenant', in: 'header', required: true },
        { name: 'sid', in: 'cookie', required: true },
      ],
    });
    expect(toCurl(e, 'http://h').command).toBe(["curl 'http://h/it'\\''s?q=example'", "-H 'x-tenant: 1'", "-b 'sid=1'"].join(' \\\n  '));
  });
});

describe('toHttpFile', () => {
  it('shares variables across requests and gives each base URL its own variable', () => {
    const endpoints = [
      ep('GET', '/users/:id', { controller: 'UsersController', handler: 'findOne', parameters: [{ name: 'id', in: 'path', required: true, type: 'string' }] }),
      ep('DELETE', '/users/:id', { handler: '(anonymous)', auth: { status: 'protected', via: ['authenticate'] } }),
      ep('GET', '/products/{id}', { framework: 'spring', projectRoot: '/s', parameters: [{ name: 'page', in: 'query', required: false }] }),
    ];
    const text = toHttpFile(endpoints, { title: 'Demo API', baseUrl: (e) => baseUrlFor(e, { baseUrl: '', servers: [] }), relativePath: (f) => f.replace('/p/', '') });
    expect(text).toBe(
      [
        '# Demo API',
        '# Generated by API Shadow. Values are placeholders; edit the variables below.',
        '',
        '@baseUrl = http://localhost:8080',
        '@baseUrl2 = http://localhost:3000',
        '@id = 1',
        '@token = ',
        '',
        '### GET /products/{id}',
        '# src/routes/users.js:7',
        '# Optional query parameters: page',
        'GET {{baseUrl}}/products/{{id}}',
        '',
        '### DELETE /users/:id',
        '# src/routes/users.js:7',
        'DELETE {{baseUrl2}}/users/{{id}}',
        'Authorization: Bearer {{token}}',
        '',
        '### GET /users/:id',
        '# UsersController.findOne · src/routes/users.js:7',
        'GET {{baseUrl2}}/users/{{id}}',
        '',
      ].join('\n'),
    );
  });

  it('leaves out locations when asked and has no header for a single request', () => {
    const text = toHttpFile([ep('PATCH', '/a')], { baseUrl: () => 'http://h' });
    expect(text).toBe(['@baseUrl = http://h', '', '### PATCH /a', 'PATCH {{baseUrl}}/a', 'Content-Type: application/json', '', '{}', ''].join('\n'));
  });
});

describe('Auth in filters and exports', () => {
  const open = ep('POST', '/orders', { auth: { status: 'none', via: [] } });
  const closed = ep('GET', '/users', { auth: { status: 'protected', via: ['authenticate'] } });

  it('filters by auth status', () => {
    expect(matchesFilter(open, { text: 'auth:none', methods: new Set() })).toBe(true);
    expect(matchesFilter(closed, { text: 'auth:none', methods: new Set() })).toBe(false);
    expect(matchesFilter(closed, { text: 'auth:protected users', methods: new Set() })).toBe(true);
  });

  it('lists endpoints without auth in the Markdown export, separate from limitations', () => {
    const md = toMarkdown(
      {
        endpoints: [open, closed],
        issues: [{ kind: 'no-auth', severity: 'warning', message: 'No auth found for POST /orders', location: open.location, endpointIds: [open.id] }],
        duplicates: [],
        servers: [],
        clientCalls: [],
        stats: { filesDiscovered: 0, filesAnalyzed: 0, filesFromCache: 0, filesSkipped: 0, durationMs: 0, truncated: false },
      },
      { title: 't', relativePath: (f) => f },
    );
    expect(md).toContain('## Endpoints without detected auth\n\nOther endpoints in the same project use auth middleware, guards or security annotations; these do not.\n\n- POST `/orders` — /p/src/routes/users.js:7\n');
    expect(md).not.toContain('Analysis notes and limitations');
  });
});

import type { AnalysisResult, Endpoint } from '../core/types';

export interface ExportOptions {
  title: string;
  /** Maps absolute paths to the form shown in the export (usually workspace-relative). */
  relativePath: (file: string) => string;
  /** Include file:line locations (default true). */
  includeSourceLocations?: boolean;
}

function escapeCell(value: string): string {
  return value.replace(/\\/g, '\\\\').replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');
}

function code(value: string): string {
  const v = value.replace(/`/g, 'ˋ');
  return '`' + v + '`';
}

export function toMarkdown(result: AnalysisResult, options: ExportOptions): string {
  const includeLoc = options.includeSourceLocations !== false;
  const lines: string[] = [];
  lines.push(`# ${options.title}`, '');
  lines.push(`Generated by API Shadow on ${new Date().toISOString()} from static analysis of the source code.`, '');
  const byFramework = new Map<string, number>();
  for (const e of result.endpoints) byFramework.set(e.framework, (byFramework.get(e.framework) ?? 0) + 1);
  lines.push(`**${result.endpoints.length} endpoint(s)**` + (byFramework.size ? ` — ${[...byFramework].map(([f, n]) => `${f}: ${n}`).join(', ')}` : ''), '');

  const groups = new Map<string, Endpoint[]>();
  for (const e of [...result.endpoints].sort(compareEndpoints)) {
    const key = `${e.controller ?? '(no controller)'} (${e.framework})`;
    const list = groups.get(key) ?? [];
    list.push(e);
    groups.set(key, list);
  }
  for (const [group, list] of groups) {
    lines.push(`## ${group}`, '');
    const header = ['Method', 'Path', 'Handler', 'Middleware / Guards', 'Services'];
    if (includeLoc) header.push('Source');
    lines.push(`| ${header.join(' | ')} |`, `|${header.map(() => '---').join('|')}|`);
    for (const e of list) {
      const row = [
        e.method,
        code(e.path) + (e.pathIsStatic ? '' : ' ⚠'),
        e.handler ? code(e.handler) : '',
        e.middleware.map(code).join(', '),
        e.services.map((s) => code(s.name)).join(', '),
      ];
      if (includeLoc) row.push(`${options.relativePath(e.location.file)}:${e.location.line}`);
      lines.push(`| ${row.map(escapeCell).join(' | ')} |`);
    }
    lines.push('');
  }

  if (result.duplicates.length > 0) {
    lines.push('## Potential duplicate routes', '');
    const byId = new Map(result.endpoints.map((e) => [e.id, e]));
    for (const d of result.duplicates) {
      const locs = d.endpointIds
        .map((id) => byId.get(id))
        .filter((e): e is Endpoint => !!e)
        .map((e) => (includeLoc ? `${options.relativePath(e.location.file)}:${e.location.line}` : e.handler ?? e.path));
      lines.push(`- ${d.method} ${code(d.path)} — ${locs.join(', ')}`);
    }
    lines.push('');
  }

  const limitations = result.issues.filter((i) => i.kind !== 'duplicate');
  if (limitations.length > 0) {
    lines.push('## Analysis notes and limitations', '');
    for (const i of limitations) {
      const where = includeLoc && i.location ? ` (${options.relativePath(i.location.file)}:${i.location.line})` : '';
      lines.push(`- **${i.severity}**: ${escapeCell(i.message)}${where}`);
    }
    lines.push('');
  }
  lines.push('> ⚠ marks paths that contain parts API Shadow could not resolve statically.', '');
  return lines.join('\n');
}

export function compareEndpoints(a: Endpoint, b: Endpoint): number {
  return a.path.localeCompare(b.path) || a.method.localeCompare(b.method) || a.location.file.localeCompare(b.location.file) || a.location.line - b.location.line;
}

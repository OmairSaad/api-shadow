/**
 * The full API Shadow report in Markdown: overview, coverage findings (Hidden API Hunter),
 * change impact, security findings and the endpoint inventory. Every finding has its source
 * location; heuristic findings are labelled as such.
 */
import type { ImpactReport } from '../core/impact';
import { describeShape, successShape } from '../core/shapes';
import { SECURITY_RULES } from '../core/security';
import { summarize } from '../core/summary';
import type { AnalysisResult, Endpoint, SourceLocation } from '../core/types';
import { compareEndpoints } from './markdown';

export interface ReportOptions {
  title: string;
  relativePath: (file: string) => string;
  impact?: ImpactReport;
  /** Finding ids the user dismissed; listed separately. */
  dismissed?: ReadonlySet<string>;
}

function cell(v: string): string {
  return v.replace(/\\/g, '\\\\').replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');
}

function code(v: string): string {
  return '`' + v.replace(/`/g, 'ˋ') + '`';
}

export function toReport(result: AnalysisResult, o: ReportOptions): string {
  const s = summarize(result, o.impact);
  const at = (l: SourceLocation | undefined): string => (l ? `${o.relativePath(l.file)}:${l.line}` : '');
  const lines: string[] = [`# ${o.title}`, '', `Generated by API Shadow on ${new Date().toISOString()} from static analysis. Nothing was executed and no code left this machine.`, ''];

  lines.push('## Overview', '');
  lines.push('| | |', '|---|---|');
  lines.push(`| Endpoints | ${s.endpoints} (${Object.entries(s.byMethod).map(([m, n]) => `${m} ${n}`).join(', ') || 'none'}) |`);
  lines.push(`| Frameworks | ${Object.entries(s.byFramework).map(([f, n]) => `${f} ${n}`).join(', ') || 'none'} |`);
  lines.push(`| Path confidence | ${s.confidence.high} resolved, ${s.confidence.medium} relative to an unmounted router, ${s.confidence.low} with unresolved parts |`);
  lines.push(`| Frontend requests | ${s.calls.app} (${s.calls.matched} matched, ${s.calls.unmatched} unmatched, ${s.calls.ambiguous} ambiguous) |`);
  lines.push(`| Test requests | ${s.calls.test} |`);
  lines.push(`| Potentially unused routes | ${s.potentiallyUnused} |`);
  lines.push(`| Reads of fields the response does not have | ${s.responseMismatches} |`);
  if (s.impact) lines.push(`| Potential breaking changes since ${cell(s.impact.baseLabel)} | ${s.impact.high} high, ${s.impact.medium} medium, ${s.impact.low} low |`);
  lines.push(`| Security findings | ${s.security.high} high, ${s.security.medium} medium, ${s.security.low} low, ${s.security.info} info |`);
  lines.push('');

  // Change impact
  if (o.impact && o.impact.endpoints.length) {
    lines.push(`## Change impact since ${o.impact.baseLabel}`, '');
    for (const e of o.impact.endpoints) {
      lines.push(`### ${e.risk.toUpperCase()} · ${e.method} ${code(e.path)} (${e.status})`, '');
      for (const c of e.changes) {
        lines.push(`- ${c.breaking ? '⚠️ ' : ''}${cell(c.text)} — risk **${c.risk}**, ${c.evidence}. ${cell(c.reason)}`);
        for (const r of c.reads) lines.push(`  - reads ${code(r.path)} in ${r.within ?? 'code'} (${at(r.location)})${r.suggestion ? ` — suggested: use ${code(r.suggestion.to)}` : ''}`);
      }
      if (e.callers.length) lines.push(`- Callers: ${e.callers.map((c) => `${c.within ?? c.client} (${at(c.location)})`).join(', ')}`);
      lines.push('');
    }
  }

  // Coverage findings
  const byId = new Map(result.endpoints.map((e) => [e.id, e]));
  const hunter: [string, string, string[]][] = [];
  const unmatched = result.clientCalls.filter((c) => c.kind === 'app' && c.endpointIds.length === 0);
  hunter.push([
    'Unmatched frontend requests',
    'Requests in app code that match no discovered route. Calls to other services are included when their path looks like this API; a dynamic URL may hide the real route.',
    unmatched.map((c) => `${c.method === 'ALL' ? '' : c.method + ' '}${code(c.url)} (${c.client}, ${at(c.location)})`),
  ]);
  const calledProjects = new Set(result.endpoints.filter((e) => (e.usage?.calls ?? 0) > 0).map((e) => e.projectRoot));
  hunter.push([
    'Potentially unused routes',
    'No code in the workspace calls these. Mobile apps, other services, scheduled jobs or external clients may still use them.',
    result.endpoints.filter((e) => calledProjects.has(e.projectRoot) && (e.usage?.calls ?? 0) === 0).map((e) => `${e.method} ${code(e.path)} (${at(e.location)})`),
  ]);
  hunter.push([
    'Dynamic routes requiring review',
    'Paths with parts that could not be resolved statically; the real path may differ.',
    result.endpoints.filter((e) => e.confidence === 'low').map((e) => `${e.method} ${code(e.path)} (${at(e.location)})`),
  ]);
  hunter.push([
    'Routes relative to an unmounted router',
    'The router is never mounted by an analysed app (dynamic mounting, a missing file); the path lacks its prefix.',
    result.endpoints.filter((e) => e.confidence === 'medium').map((e) => `${e.method} ${code(e.path)} (${at(e.location)})`),
  ]);
  hunter.push([
    'Duplicate route candidates',
    'Routes that may compete for the same requests.',
    result.duplicates.map((d) => `${d.method} ${code(d.path)}: ${d.endpointIds.map((id) => at(byId.get(id)?.location)).join(', ')}`),
  ]);
  hunter.push(['Unreachable routes', 'An earlier route catches every request these would get.', result.issues.filter((i) => i.kind === 'unreachable').map((i) => `${cell(i.message)} (${at(i.location)})`)]);
  hunter.push(['Reads of missing response fields', 'Client code reads a field that the inferred (closed) response does not contain.', result.issues.filter((i) => i.kind === 'response-mismatch').map((i) => `${cell(i.message)} (${at(i.location)})`)]);
  const nonEmpty = hunter.filter(([, , items]) => items.length > 0);
  if (nonEmpty.length) {
    lines.push('## API coverage findings', '');
    for (const [title, note, items] of nonEmpty) {
      lines.push(`### ${title} (${items.length})`, '', `_${note}_`, '');
      for (const i of items.slice(0, 200)) lines.push(`- ${i}`);
      if (items.length > 200) lines.push(`- …and ${items.length - 200} more`);
      lines.push('');
    }
  }

  // Security
  const active = result.security.filter((f) => !o.dismissed?.has(f.id));
  if (result.security.length) {
    lines.push('## Security findings', '', '_Potential issues found by static analysis, not confirmed vulnerabilities. Severity is how bad it would be; confidence is how likely the evidence means it._', '');
    if (active.length) {
      lines.push('| Severity | Confidence | Rule | Endpoint | Location | Finding |', '|---|---|---|---|---|---|');
      for (const f of active) lines.push(`| ${f.severity} | ${f.confidence} | ${f.rule} | ${f.endpoint ? cell(f.endpoint) : ''} | ${at(f.location)} | ${cell(f.message)} |`);
      lines.push('');
      lines.push('### Recommended mitigations', '');
      for (const rule of [...new Set(active.map((f) => f.rule))]) lines.push(`- **${SECURITY_RULES[rule].title}** (${rule}): ${SECURITY_RULES[rule].mitigation}`);
      lines.push('');
    }
    const dismissed = result.security.length - active.length;
    if (dismissed) lines.push(`${dismissed} finding(s) dismissed in this workspace are not listed.`, '');
  }

  // Inventory
  lines.push('## Endpoint inventory', '');
  lines.push('| Method | Path | Handler | Auth | Callers | Response | Confidence | Source |', '|---|---|---|---|---|---|---|---|');
  for (const e of [...result.endpoints].sort(compareEndpoints)) {
    lines.push(
      `| ${e.method} | ${code(e.path)} | ${e.handler ? code(handlerName(e)) : ''} | ${e.auth?.status ?? ''} | ${e.usage ? `${e.usage.calls} app, ${e.usage.tests} test` : ''} | ${cell(responseSummary(e))} | ${e.confidence ?? ''} | ${at(e.location)} |`,
    );
  }
  lines.push('');
  const limits = result.issues.filter((i) => i.kind === 'limitation' || i.kind === 'parse-error' || i.kind === 'skipped');
  if (limits.length) {
    lines.push('## Analysis limitations', '');
    for (const i of limits) lines.push(`- **${i.severity}**: ${cell(i.message)}${i.location ? ` (${at(i.location)})` : ''}`);
    lines.push('');
  }
  lines.push('_Response shapes are inferred from handler code and declared types; they are not an API specification._', '');
  return lines.join('\n');
}

function handlerName(e: Endpoint): string {
  return e.controller && e.handler && !e.handler.includes('.') ? `${e.controller}.${e.handler}` : (e.handler ?? '');
}

function responseSummary(e: Endpoint): string {
  const s = successShape(e);
  const statuses = [...new Set((e.responses ?? []).map((r) => r.status).filter((x): x is number => x !== undefined))].sort();
  const shape = s ? describeShape(s) : '';
  return [shape.length > 60 ? shape.slice(0, 57) + '…' : shape, statuses.length ? `status ${statuses.join(', ')}` : ''].filter(Boolean).join('; ');
}

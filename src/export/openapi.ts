/**
 * OpenAPI 3.0 export. Only information that was actually found in source is emitted: paths,
 * methods, path/query/header parameters, the presence of a request body, and responses inferred
 * from handler code (status codes, and shapes built from literals or declared DTO types). Inferred
 * responses are marked `x-api-shadow-inferred`; parts whose shape is unknown get an empty schema,
 * and a `default` response documents that the list may be incomplete. Endpoints that OpenAPI
 * cannot represent exactly (wildcards, regexes, unresolved expressions, "all methods") are left
 * out and listed under `x-api-shadow.skipped`.
 */
import { toOpenApiPath } from '../core/paths';
import type { AnalysisResult, Endpoint, EndpointParameter, Shape } from '../core/types';
import { compareEndpoints, type ExportOptions } from './markdown';

export interface OpenApiExportOptions extends ExportOptions {
  version?: string;
}

interface Operation {
  operationId: string;
  summary: string;
  tags: string[];
  parameters?: unknown[];
  requestBody?: unknown;
  responses: Record<string, unknown>;
  'x-api-shadow'?: Record<string, unknown>;
}

export interface OpenApiDocument {
  openapi: '3.0.3';
  info: { title: string; version: string; description: string };
  paths: Record<string, Record<string, Operation>>;
  tags: { name: string }[];
  'x-api-shadow': { generatedAt: string; included: number; skipped: { method: string; path: string; reason: string; source?: string }[] };
}

const PRIMITIVES: Record<string, { type: string; format?: string }> = {
  string: { type: 'string' },
  String: { type: 'string' },
  UUID: { type: 'string', format: 'uuid' },
  number: { type: 'number' },
  int: { type: 'integer', format: 'int32' },
  Integer: { type: 'integer', format: 'int32' },
  long: { type: 'integer', format: 'int64' },
  Long: { type: 'integer', format: 'int64' },
  short: { type: 'integer' },
  Short: { type: 'integer' },
  double: { type: 'number', format: 'double' },
  Double: { type: 'number', format: 'double' },
  float: { type: 'number', format: 'float' },
  Float: { type: 'number', format: 'float' },
  BigDecimal: { type: 'number' },
  boolean: { type: 'boolean' },
  Boolean: { type: 'boolean' },
  LocalDate: { type: 'string', format: 'date' },
  LocalDateTime: { type: 'string', format: 'date-time' },
};

function schemaFor(type: string | undefined, pattern?: string): Record<string, unknown> {
  const base = (type && PRIMITIVES[type]) ?? { type: 'string' };
  return pattern ? { ...base, pattern } : { ...base };
}

export function toOpenApi(result: AnalysisResult, options: OpenApiExportOptions): OpenApiDocument {
  const includeLoc = options.includeSourceLocations !== false;
  const doc: OpenApiDocument = {
    openapi: '3.0.3',
    info: {
      title: options.title,
      version: options.version ?? '0.0.0',
      description:
        'Generated by API Shadow from static source analysis. Operations list only what was found in code; ' +
        'responses marked x-api-shadow-inferred are inferred from handler code and are not authoritative.',
    },
    paths: {},
    tags: [],
    'x-api-shadow': { generatedAt: new Date().toISOString(), included: 0, skipped: [] },
  };
  const tags = new Set<string>();
  const usedOperationIds = new Set<string>();
  // OpenAPI treats templates that differ only in parameter names as identical (and invalid).
  const usedTemplates = new Map<string, string>();
  const skip = (e: Endpoint, reason: string): void => {
    doc['x-api-shadow'].skipped.push({
      method: e.method,
      path: e.path,
      reason,
      source: includeLoc ? `${options.relativePath(e.location.file)}:${e.location.line}` : undefined,
    });
  };
  for (const e of [...result.endpoints].sort(compareEndpoints)) {
    if (!e.pathIsStatic) {
      skip(e, 'path contains parts that could not be resolved statically');
      continue;
    }
    if (e.method === 'ALL') {
      skip(e, 'route matches all HTTP methods');
      continue;
    }
    const conv = toOpenApiPath(e.path);
    if (!conv.path) {
      skip(e, conv.unsupportedReason ?? 'unsupported path syntax');
      continue;
    }
    const method = e.method.toLowerCase();
    const templateKey = `${method} ${conv.path.replace(/\{[^}]*\}/g, '{}')}`;
    const existing = usedTemplates.get(templateKey);
    if (existing) {
      skip(e, `duplicate of ${e.method} ${existing}`);
      continue;
    }
    usedTemplates.set(templateKey, conv.path);
    const pathItem = (doc.paths[conv.path] ??= {});
    const tag = e.controller ?? e.framework;
    tags.add(tag);
    const params: unknown[] = [];
    const declared = new Map<string, EndpointParameter>();
    for (const p of e.parameters) declared.set(`${p.in}:${p.name}`, p);
    for (const p of conv.pathParams) {
      const d = declared.get(`path:${p.name}`);
      params.push({ name: p.name, in: 'path', required: true, schema: schemaFor(d?.type, p.pattern) });
    }
    for (const p of e.parameters) {
      if (p.in === 'path') continue;
      params.push({ name: p.name, in: p.in, required: p.required, schema: schemaFor(p.type) });
    }
    const op: Operation = {
      operationId: uniqueOperationId(e, usedOperationIds),
      summary: e.handler ? `${e.controller ? e.controller + '.' : ''}${e.handler}` : `${e.method} ${e.path}`,
      tags: [tag],
      responses: { ...inferredResponses(e), default: { description: 'Other responses were not analysed by API Shadow.' } },
    };
    if (params.length > 0) op.parameters = params;
    if (e.requestBodyType) {
      op.requestBody = {
        required: true,
        description: `Request body of type ${e.requestBodyType} (schema not inferred).`,
        content: { 'application/json': { schema: {} } },
      };
    }
    const ext: Record<string, unknown> = { framework: e.framework };
    if (includeLoc) ext.source = `${options.relativePath(e.location.file)}:${e.location.line}`;
    if (e.middleware.length > 0) ext.middleware = e.middleware;
    if (e.services.length > 0) ext.services = e.services.map((s) => s.name);
    op['x-api-shadow'] = ext;
    pathItem[method] = op;
    doc['x-api-shadow'].included++;
  }
  doc.tags = [...tags].sort().map((name) => ({ name }));
  return doc;
}

function uniqueOperationId(e: Endpoint, used: Set<string>): string {
  const base = (`${e.controller ?? ''}_${e.handler ?? ''}`.replace(/^_|_$/g, '') || `${e.method}_${e.path}`)
    .replace(/[^A-Za-z0-9_]+/g, '_')
    .replace(/^_+|_+$/g, '') || 'operation';
  let id = base;
  for (let i = 2; used.has(id); i++) id = `${base}_${i}`;
  used.add(id);
  return id;
}

/** Responses inferred from handler code, keyed by status code. */
function inferredResponses(e: Endpoint): Record<string, unknown> {
  const out: Record<string, { description: string; content?: unknown; 'x-api-shadow-inferred': true }> = {};
  for (const r of e.responses ?? []) {
    const status = String(r.status ?? (e.framework === 'nestjs' && e.method === 'POST' ? 201 : 200));
    if (!/^[1-5]\d\d$/.test(status)) continue;
    const existing = out[status];
    const description = r.via === 'type' && r.type ? `${r.type} (declared return type)` : r.via === 'throw' ? 'Thrown HTTP exception' : 'Inferred from handler code';
    if (!existing) out[status] = { description, 'x-api-shadow-inferred': true };
    const target = out[status];
    if (r.shape && r.shape.t !== 'unknown' && !target.content) target.content = { 'application/json': { schema: toSchema(r.shape, 0) } };
  }
  return out;
}

function toSchema(s: Shape, depth: number): Record<string, unknown> {
  if (depth > 8) return {};
  switch (s.t) {
    case 'object': {
      const properties: Record<string, unknown> = {};
      const required: string[] = [];
      for (const [k, p] of Object.entries(s.props)) {
        properties[k] = toSchema(p.shape, depth + 1);
        if (!p.optional) required.push(k);
      }
      const out: Record<string, unknown> = { type: 'object', properties };
      if (required.length && !s.open) out.required = required;
      return out;
    }
    case 'array':
      return { type: 'array', items: s.items ? toSchema(s.items, depth + 1) : {} };
    case 'string':
    case 'number':
    case 'boolean':
      return { type: s.t };
    case 'null':
      return { nullable: true };
    default:
      return {};
  }
}
